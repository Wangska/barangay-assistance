const { chromium } = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
 const preview=JSON.parse(fs.readFileSync('outputs/capstone_preview.json','utf8'));
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try {
  const context=await browser.newContext({viewport:{width:1365,height:950}});
  const page=await context.newPage();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(preview.url+'/login.php');
  await page.locator('input[name=email]').fill(preview.email);
  await page.locator('input[name=password]').fill(preview.password);
  await Promise.all([page.waitForURL('**/senior/dashboard.php'),page.locator('button[type=submit]').click()]);
  await page.goto(preview.url+'/senior/application.php');
  await page.locator('#interface-language').selectOption('ceb');
  assert.equal(await page.locator('h1').textContent(),'Pagsubay sa aplikasyon');
  await page.locator('#larger-text').click();
  assert.equal(await page.locator('#larger-text').getAttribute('aria-pressed'),'true');
  await page.reload();
  assert.equal(await page.locator('#interface-language').inputValue(),'ceb');
  assert.equal(await page.locator('#larger-text').getAttribute('aria-pressed'),'true');
  await page.screenshot({path:'outputs/application-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  const sizes=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  assert(sizes.scroll<=sizes.width+1,'No horizontal document overflow on mobile');
  await page.screenshot({path:'outputs/application-mobile.png',fullPage:true});
  await page.locator('#interface-language').selectOption('en');
  await page.goto(preview.url+'/senior/notifications.php?filter=unread');
  assert(await page.locator('a:has-text("View details")').count()>0);
  const initial=Number(await page.locator('[data-notification-count]').textContent());
  const staffContext=await browser.newContext();
  const staff=await staffContext.newPage();
  await staff.goto(preview.url+'/login.php');
  await staff.locator('input[name=email]').fill('staff@example.invalid');
  await staff.locator('input[name=password]').fill(preview.password);
  await Promise.all([staff.waitForURL('**/staff/dashboard.php'),staff.locator('button[type=submit]').click()]);
  await staff.goto(preview.url+'/staff/announcements.php');
  await staff.locator('input[name=title]').fill('Browser verification');
  await staff.locator('input[name=body]').fill('New notification count should refresh.');
  await Promise.all([staff.waitForURL('**/staff/announcements.php'),staff.getByRole('button',{name:'Post',exact:true}).click()]);
  const deadline=Date.now()+40000;
  while(Date.now()<deadline && Number(await page.locator('[data-notification-count]').textContent())<=initial) await page.waitForTimeout(1000);
  assert(Number(await page.locator('[data-notification-count]').textContent())>initial,'Automatic unread count updates');
  assert(await page.locator('[data-notification-update]').isVisible(),'New-notification banner appears');
  assert.deepEqual(errors,[]);
  console.log('PASS: language switching, persistent larger text, desktop/mobile layout, direct links, automatic unread count, and update banner.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});